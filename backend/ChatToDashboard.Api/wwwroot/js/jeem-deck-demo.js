  function build(t) {
    const data = DATA[t.key] || [];
    const slides = (t.slides || []).map((s, i) => {
      const base = { id: 'demo-' + i, layout: s.layout, title: s.layout === 'title' ? t.name : s.title };
      if (s.layout === 'chart' && s.hint) base.chart = { type: s.hint };
      const extra = data[i] && Object.keys(data[i]).length ? data[i] : fallback(base, i);
      if (base.layout === 'tasks') base.editable = { key: 'demo-tasks-' + i, kind: 'tasks' };
      return Object.assign(base, extra);
    });
    return { title: t.name, subtitle: (data[0] && data[0].subtitle) || '', slides };
  }

