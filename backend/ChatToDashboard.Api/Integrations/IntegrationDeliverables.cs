        </div>
        <script>
        const CONFIG = {{configJson}};
        const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

        {{IdentityTransportJs}}

        let dashboards = [];
        // In-memory per-dashboard state: { mode: 'everyone'|'restricted', allowed: [{id,label,kind}] }
        const state = {};

        async function init() {
          if (!CONFIG.readApiBaseUrl) {
            document.getElementById('list').innerHTML = '<div class="state-msg">لم يتم ضبط نقطة القراءة (Read API) لهذا التكامل بعد.</div>';
            return;
          }
          try {
            // Calls the exact same read endpoint viewer.html does, with the exact same identity
            // mechanism — your connector must recognize the identity this admin session sends as
            // one of its own configured AdminIdentifiers, or any dashboard this page restricts
            // without also allow-listing that identity disappears from this very list on the
            // next load. See the connector's own README (ConnectorOptions.AdminIdentifiers).
            const res = await fetchWithIdentity(CONFIG.readApiBaseUrl);
            if (!res.ok) throw new Error('HTTP ' + res.status);
            let body = await res.json();
            dashboards = Array.isArray(body) ? body : (body.dashboards || []);
          } catch (err) {
            document.getElementById('list').innerHTML = '<div class="state-msg">تعذّر تحميل قائمة اللوحات: ' + esc(err.message) + '</div>';
            return;
          }
          dashboards.forEach(d => {
            const id = d.dashboardId || d.id;
            state[id] = { mode: d.permissionMode || 'everyone', allowed: d.allowedIdentifiers || [] };
          });
          render();
        }

        function render() {
          const list = document.getElementById('list');
          if (dashboards.length === 0) { list.innerHTML = '<div class="state-msg">لا توجد لوحات منشورة بعد.</div>'; return; }
          list.innerHTML = dashboards.map(d => rowHtml(d.dashboardId || d.id, d.title || d.dashboardId || d.id)).join('');
          dashboards.forEach(d => wireRow(d.dashboardId || d.id));
        }

        function rowHtml(id, title) {
          const s = state[id];
          const everyone = s.mode !== 'restricted';
          const warn = !everyone && s.allowed.length === 0
            ? '<div class="empty-warning">هذه اللوحة مقيّدة ولا تحتوي على أي معرّف مسموح — لن تظهر لأي أحد حتى تضيف واحدًا.</div>' : '';
          return '<div class="dash-row" data-id="' + esc(id) + '">' +
            '<div class="dash-row-head"><span class="dash-title">' + esc(title) + '</span>' +
            '<div class="toggle-group">' +
              '<button type="button" class="toggle-btn everyone-btn' + (everyone ? ' active' : '') + '">للجميع</button>' +
              '<button type="button" class="toggle-btn restricted-btn' + (!everyone ? ' active' : '') + '">مقيّدة</button>' +
            '</div></div>' +
            '<div class="restricted-panel' + (!everyone ? ' open' : '') + '">' +
              '<div class="chip-list"></div>' +
              '<div class="search-row"><input type="text" placeholder="ابحث بالاسم أو أضف يدويًا…" autocomplete="off" /><div class="suggestions" style="display:none"></div></div>' +
              warn +
              '<div style="margin-top:10px"><button type="button" class="toggle-btn save-btn" style="background:var(--accent);color:#fff">حفظ</button><span class="save-note"></span></div>' +
            '</div></div>';
        }

        function wireRow(id) {
          const row = document.querySelector('.dash-row[data-id="' + CSS.escape(id) + '"]');
          const s = state[id];
          const panel = row.querySelector('.restricted-panel');
          const chipList = row.querySelector('.chip-list');

          function renderChips() {
            chipList.innerHTML = s.allowed.map((a, i) =>
              '<span class="chip">' + esc(a.label) + (a.kind ? ' <span class="suggestion-tag">(' + esc(a.kind === 'role' ? 'دور' : 'مستخدم') + ')</span>' : '') +
              '<button type="button" data-i="' + i + '">✕</button></span>').join('');
            chipList.querySelectorAll('button').forEach(btn => btn.addEventListener('click', () => {
              s.allowed.splice(Number(btn.dataset.i), 1);
              renderChips();
              updateWarning();
            }));
          }
          function updateWarning() {
            let warn = panel.querySelector('.empty-warning');
            const shouldWarn = s.mode === 'restricted' && s.allowed.length === 0;
            if (shouldWarn && !warn) {
              warn = document.createElement('div');
              warn.className = 'empty-warning';
              warn.textContent = 'هذه اللوحة مقيّدة ولا تحتوي على أي معرّف مسموح — لن تظهر لأي أحد حتى تضيف واحدًا.';
              panel.querySelector('.search-row').after(warn);
            } else if (!shouldWarn && warn) {
              warn.remove();
            }
          }
          renderChips();

          row.querySelector('.everyone-btn').addEventListener('click', () => {
            s.mode = 'everyone';
            row.querySelector('.everyone-btn').classList.add('active');
            row.querySelector('.restricted-btn').classList.remove('active');
            panel.classList.remove('open');
          });
          row.querySelector('.restricted-btn').addEventListener('click', () => {
            s.mode = 'restricted';
            row.querySelector('.restricted-btn').classList.add('active');
            row.querySelector('.everyone-btn').classList.remove('active');
            panel.classList.add('open');
            updateWarning();
          });

          const input = row.querySelector('.search-row input');
          const suggestions = row.querySelector('.suggestions');
          let searchTimer = null;
          input.addEventListener('input', () => {
            clearTimeout(searchTimer);
            const q = input.value.trim();
            if (!q || !CONFIG.directoryApiUrl) { suggestions.style.display = 'none'; return; }
            searchTimer = setTimeout(async () => {
              try {
                const res = await fetchWithIdentity(CONFIG.directoryApiUrl + '?q=' + encodeURIComponent(q));
                if (!res.ok) throw new Error();
                const results = await res.json();
                const items = Array.isArray(results) ? results : (results.results || []);
                if (!items.length) { suggestions.style.display = 'none'; return; }
                suggestions.innerHTML = items.map((r, i) =>
                  '<div class="suggestion-item" data-i="' + i + '"><span>' + esc(r.label || r.name) + '</span>' +
                  '<span class="suggestion-tag">' + esc(r.kind === 'role' ? 'دور' : 'مستخدم') + '</span></div>').join('');
                suggestions.style.display = 'block';
                suggestions.querySelectorAll('.suggestion-item').forEach(el => el.addEventListener('click', () => {
                  const r = items[Number(el.dataset.i)];
                  s.allowed.push({ id: r.id, label: r.label || r.name, kind: r.kind || 'user' });
                  input.value = '';
                  suggestions.style.display = 'none';
                  renderChips();
                  updateWarning();
                }));
              } catch { suggestions.style.display = 'none'; }
            }, 250);
          });
          // Manual fallback — Directory API absent or the analyst just types a raw identifier
          // and presses Enter, per Part E: "never block on the Directory API's availability."
          input.addEventListener('keydown', e => {
            if (e.key !== 'Enter') return;
            e.preventDefault();
            const value = input.value.trim();
            if (!value) return;
            s.allowed.push({ id: value, label: value, kind: null });
            input.value = '';
            suggestions.style.display = 'none';
            renderChips();
            updateWarning();
          });

          row.querySelector('.save-btn').addEventListener('click', async () => {
            const note = row.querySelector('.save-note');
