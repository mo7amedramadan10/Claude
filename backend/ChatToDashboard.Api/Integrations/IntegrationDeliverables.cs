namespace ChatToDashboard.Api.Integrations;

/// <summary>
/// Generates the three self-contained deliverables handed to a client. Deliverables 1 and 2
/// (Part D and Part E) are single HTML files with their own config baked in at generation time
/// (read/directory/permissions API URLs, the confirmed identity-transport mechanism, the
/// visual-identity tokens) — nothing in either one calls back to our own backend at view-time,
/// per Part D/E's "no dependency on our systems at view-time" requirement. Deliverable 3 is the
/// connector microservice source (../IntegrationConnector, embedded into this assembly — see
/// this project's .csproj) that the client builds and deploys themselves, pre-filled with
/// whatever of its config this integration's settings already answer.
///
/// Widget rendering (Deliverables 1/2) covers the five core types (kpi/bar/line/pie/table) via
/// Chart.js from a CDN — a deliberate, documented scope choice: reproducing every specialized
/// widget type this app's own design system has (progress-table/trend-matrix/status-bar/radial-
/// gauge/linear-gauge) inside a hand-generated single file would be its own multi-week effort;
/// an unrecognized type falls back to a plain key/value table so nothing silently disappears.
/// </summary>
public class IntegrationDeliverables
{
    public string BuildViewerHtml(ExternalIntegration integration)
    {
        var tokens = ResolveTokens(integration);
        var config = new
        {
            readApiBaseUrl = integration.DashboardsUrl ?? "",
            identity = new
            {
                mechanism = integration.IdentityConfirmed ? integration.IdentityMechanism : null,
                parameterName = integration.IdentityConfirmed ? integration.IdentityParameterName : null,
            },
            accent = tokens.Accent,
            secondary = tokens.Secondary,
            font = tokens.Font,
            integrationName = integration.Name,
        };
        var configJson = JsonSerializer.Serialize(config, new JsonSerializerOptions { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping });
        // Inlined, never fetched — a client's network may allow nothing but its own domains
        // (this stopped an actual deployment cold: the CDN request was blocked outright), and
        // this file is meant to work inside exactly that kind of locked-down network.
        // Defensive: a literal "</script" inside the embedded JS would close the tag early as
        // far as the HTML parser is concerned, regardless of it being inside a JS string — none
        // in the vendored 4.4.4 build today, but this guards a future version bump too.
        var chartJs = ReadEmbeddedText("vendor.chart.umd.js").Replace("</script", "<\\/script", StringComparison.OrdinalIgnoreCase);

        return $$"""
        <!doctype html>
        <html lang="ar" dir="rtl">
        <head>
        <meta charset="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <title>لوحات المتابعة</title>
        <meta name="x-integration-name" content="{{Escape(integration.Name)}}" />
        <!--
          Generated by غرفة القيادة — see the integration name in the meta tag just above (never
          put inside this comment itself: an integration name containing "--" would prematurely
          close an HTML comment under the stricter SGML-style comment rule several non-browser
          HTML parsers/sanitizers still follow, corrupting everything after it).
          Fully self-contained: Chart.js (for bar/line/pie rendering) is embedded below, never
          fetched from anywhere. No dependency on غرفة القيادة's own systems at view-time either —
          every data call below goes to READ_API_BASE_URL only, which you host.
          Regenerate this file from غرفة القيادة after changing the read API URL, the identity-
          transport mechanism, or the visual identity — it is not fetched or updated remotely.
        -->
        <script>{{chartJs}}</script>
        <style>
        {{BaseCss(tokens)}}
        .tabbar{display:flex;gap:6px;flex-wrap:wrap;padding:14px 18px;border-bottom:1px solid var(--grid);overflow-x:auto}
        .tab{padding:8px 16px;border:1px solid var(--grid);border-radius:999px;background:var(--surface);
          color:var(--ink-2);font-size:13px;font-weight:600;cursor:pointer;white-space:nowrap}
        .tab.active{background:var(--accent-soft);color:var(--accent);border-color:var(--accent)}
        .content{padding:18px}
        .dash-summary{margin:0 0 16px;color:var(--ink-2);font-size:14px;line-height:1.7}
        .grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(280px,1fr));gap:14px}
        .widget{position:relative;background:var(--surface);border:1px solid var(--grid);border-radius:14px;padding:16px}
        .widget h3{margin:0 0 10px;font-size:13px;font-weight:700;color:var(--ink-2)}
        .widget.kpi{display:flex;flex-direction:column;align-items:center;justify-content:center;text-align:center;min-height:120px}
        .kpi-value{font-size:30px;font-weight:800;color:var(--accent)}
        table.data-table{width:100%;border-collapse:collapse;font-size:13px}
        table.data-table th,table.data-table td{padding:7px 9px;border-bottom:1px solid var(--grid);text-align:start}
        table.data-table th{color:var(--ink-2);font-weight:700}
        .src-btn{position:absolute;top:12px;inset-inline-start:12px;width:20px;height:20px;border:1px solid var(--accent);
          border-radius:50%;background:var(--accent-soft);color:var(--accent);font-size:11px;cursor:pointer;padding:0}
        .src-pop{display:none;position:absolute;top:38px;inset-inline-start:12px;z-index:20;width:min(280px,85%);
          background:var(--surface);border:1px solid var(--grid);border-radius:10px;box-shadow:0 8px 24px rgba(0,0,0,.15);
          padding:10px 12px;font-size:12px;line-height:1.7;color:var(--ink-2)}
        .src-pop.open{display:block}
        .state-msg{padding:40px;text-align:center;color:var(--ink-2)}
        canvas{max-height:240px}
        </style>
        </head>
        <body>
        <div id="tabbar" class="tabbar"></div>
        <div id="content" class="content"><div class="state-msg">جارٍ التحميل…</div></div>
        <script>
        const CONFIG = {{configJson}};
        const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

        {{IdentityTransportJs}}

        let dashboards = [];
        let activeId = null;
        const chartInstances = [];

        async function init() {
          if (!CONFIG.readApiBaseUrl) {
            document.getElementById('content').innerHTML = '<div class="state-msg">لم يتم ضبط نقطة القراءة (Read API) لهذا التكامل بعد.</div>';
            return;
          }
          try {
            const res = await fetchWithIdentity(CONFIG.readApiBaseUrl);
            if (!res.ok) throw new Error('HTTP ' + res.status);
            dashboards = await res.json();
            if (!Array.isArray(dashboards)) dashboards = dashboards.dashboards || [];
          } catch (err) {
            document.getElementById('content').innerHTML = '<div class="state-msg">تعذّر تحميل قائمة اللوحات: ' + esc(err.message) + '</div>';
            return;
          }
          if (dashboards.length === 0) {
            document.getElementById('content').innerHTML = '<div class="state-msg">لا توجد لوحات متاحة لك حاليًا.</div>';
            return;
          }
          renderTabs();
          openDashboard(dashboards[0].dashboardId || dashboards[0].id);
        }

        function renderTabs() {
          const bar = document.getElementById('tabbar');
          bar.innerHTML = dashboards.map(d => {
            const id = d.dashboardId || d.id;
            return '<button type="button" class="tab' + (id === activeId ? ' active' : '') + '" data-id="' + esc(id) + '">' + esc(d.title || id) + '</button>';
          }).join('');
          bar.querySelectorAll('.tab').forEach(btn => btn.addEventListener('click', () => openDashboard(btn.dataset.id)));
        }

        async function openDashboard(id) {
          activeId = id;
          renderTabs();
          const content = document.getElementById('content');
          content.innerHTML = '<div class="state-msg">جارٍ التحميل…</div>';
          chartInstances.forEach(c => c.destroy());
          chartInstances.length = 0;
          try {
            const url = CONFIG.readApiBaseUrl.replace(/\/$/, '') + '/' + encodeURIComponent(id);
            const res = await fetchWithIdentity(url);
            if (!res.ok) throw new Error('HTTP ' + res.status);
            const dashboard = await res.json();
            renderDashboard(dashboard);
          } catch (err) {
            content.innerHTML = '<div class="state-msg">تعذّر تحميل هذه اللوحة: ' + esc(err.message) + '</div>';
          }
        }

        function renderDashboard(d) {
          const content = document.getElementById('content');
          const summary = d.summary ? '<p class="dash-summary">' + esc(d.summary) + '</p>' : '';
          content.innerHTML = summary + '<div class="grid" id="widget-grid"></div>';
          const grid = document.getElementById('widget-grid');
          (d.widgets || []).forEach((w, i) => grid.appendChild(buildWidget(w, i)));
        }

        function buildWidget(w, index) {
          const card = document.createElement('div');
          card.className = 'widget ' + esc(w.type || '');
          const canConvertSource = !!w.source;
          card.innerHTML =
            (canConvertSource ? '<button type="button" class="src-btn" data-i="' + index + '">ⓘ</button>' +
              '<div class="src-pop" id="src-pop-' + index + '">' + esc(w.source) + '</div>' : '') +
            '<h3>' + esc(w.title || '') + '</h3>' +
            '<div class="widget-body" id="widget-body-' + index + '"></div>';

          const body = card.querySelector('.widget-body');
          renderWidgetBody(body, w, index);

          const srcBtn = card.querySelector('.src-btn');
          if (srcBtn) srcBtn.addEventListener('click', e => {
            e.stopPropagation();
            document.querySelectorAll('.src-pop.open').forEach(p => p.classList.remove('open'));
            document.getElementById('src-pop-' + index).classList.add('open');
          });
          return card;
        }

        function renderWidgetBody(body, w, index) {
          const type = (w.type || '').toLowerCase();
          const data = Array.isArray(w.data) ? w.data : (w.data ? [w.data] : []);
          if (type === 'kpi') {
            // The retargeted query's result column is never guaranteed to be named "value" —
            // it's whatever name the client's own schema (or the retargeting step) gave it — so
            // fall back to the first column of the first row, same "just take what's there"
            // approach the bar/line/pie x/yKey fallback below uses.
            const row0 = data[0] || {};
            const value = ('value' in row0) ? row0.value : (Object.values(row0)[0] ?? w.value ?? '—');
            body.innerHTML = '<div class="kpi-value">' + esc(value) + '</div>';
            return;
          }
          if (type === 'table') {
            body.appendChild(buildTable(data));
            return;
          }
          if ((type === 'bar' || type === 'line' || type === 'pie') && window.Chart && data.length) {
            const canvas = document.createElement('canvas');
            body.appendChild(canvas);
            const xKey = w.xKey || Object.keys(data[0]).find(k => typeof data[0][k] === 'string') || Object.keys(data[0])[0];
            const yKey = w.yKey || Object.keys(data[0]).find(k => typeof data[0][k] === 'number') || Object.keys(data[0])[1];
            const labels = data.map(r => r[xKey]);
            const values = data.map(r => Number(r[yKey]) || 0);
            const chart = new Chart(canvas, {
              type: type === 'pie' ? 'pie' : type,
              data: { labels, datasets: [{ label: w.title || '', data: values,
                backgroundColor: type === 'pie' ? PIE_COLORS(values.length) : CONFIG.accent,
                borderColor: CONFIG.accent, borderWidth: type === 'line' ? 2 : 1 }] },
              options: { responsive: true, plugins: { legend: { display: type === 'pie' } } },
            });
            chartInstances.push(chart);
            return;
          }
          // Unrecognized/specialized widget type — graceful fallback so nothing disappears silently.
          body.appendChild(buildTable(data));
        }

        function buildTable(rows) {
          const table = document.createElement('table');
          table.className = 'data-table';
          if (!rows.length) { table.innerHTML = '<tbody><tr><td>لا توجد بيانات.</td></tr></tbody>'; return table; }
          const keys = Object.keys(rows[0]);
          table.innerHTML =
            '<thead><tr>' + keys.map(k => '<th>' + esc(k) + '</th>').join('') + '</tr></thead>' +
            '<tbody>' + rows.map(r => '<tr>' + keys.map(k => '<td>' + esc(r[k]) + '</td>').join('') + '</tr>').join('') + '</tbody>';
          return table;
        }

        function PIE_COLORS(n) {
          const base = [CONFIG.accent, CONFIG.secondary, '#94A3B8', '#F2B84B', '#22C55E', '#EF6461'];
          const out = [];
          for (let i = 0; i < n; i++) out.push(base[i % base.length]);
          return out;
        }

        document.addEventListener('click', () => document.querySelectorAll('.src-pop.open').forEach(p => p.classList.remove('open')));
        init();
        </script>
        </body>
        </html>
        """;
    }

    public string BuildPermissionsAdminHtml(ExternalIntegration integration)
    {
        var tokens = ResolveTokens(integration);
        var config = new
        {
            readApiBaseUrl = integration.DashboardsUrl ?? "",
            directoryApiUrl = integration.DirectoryUrl ?? "",
            permissionsApiUrl = integration.PermissionsUrl ?? "",
            identity = new
            {
                mechanism = integration.IdentityConfirmed ? integration.IdentityMechanism : null,
                parameterName = integration.IdentityConfirmed ? integration.IdentityParameterName : null,
            },
            accent = tokens.Accent,
            secondary = tokens.Secondary,
            font = tokens.Font,
        };
        var configJson = JsonSerializer.Serialize(config, new JsonSerializerOptions { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping });

        return $$"""
        <!doctype html>
        <html lang="ar" dir="rtl">
        <head>
