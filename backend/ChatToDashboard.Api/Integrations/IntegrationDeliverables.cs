    /// <summary>Shared by both deliverables — turns the confirmed identity-transport mechanism
    /// into an actual fetchWithIdentity() implementation. Emits a no-op passthrough (plain
    /// fetch, no identity attached) when the integration's transport isn't confirmed yet — a
    /// half-configured integration must never silently start forwarding something, per Part C's
    /// explicit-confirmation requirement.</summary>
    private const string IdentityTransportJs = """
        function fetchWithIdentity(url) {
          const mechanism = CONFIG.identity.mechanism;
          const name = CONFIG.identity.parameterName;
          if (!mechanism || !name) return fetch(url);

          if (mechanism === 'query') {
            const value = new URLSearchParams(location.search).get(name) || '';
            const sep = url.includes('?') ? '&' : '?';
            return fetch(url + sep + encodeURIComponent(name) + '=' + encodeURIComponent(value));
          }
          if (mechanism === 'header') {
            const value = new URLSearchParams(location.search).get(name) || '';
            const headers = {}; headers[name] = value;
            return fetch(url, { headers });
          }
          // 'cookie' — the browser attaches the client-domain cookie automatically; this page
          // never reads document.cookie itself (many auth cookies are httpOnly and JS-inaccessible
          // by design). credentials:'include' just ensures it's actually sent.
          return fetch(url, { credentials: 'include' });
        }
        """;

    // Order matters: & must be escaped first, or escaping < to &lt; right before it would
    // turn that & right back into &amp;lt;.
    private static string Escape(string s) => s.Replace("&", "&amp;").Replace("\"", "&quot;").Replace("<", "&lt;").Replace(">", "&gt;");
