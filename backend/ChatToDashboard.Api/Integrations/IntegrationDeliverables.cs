        <style>
        {{BaseCss(tokens)}}
        .content{padding:20px;max-width:820px;margin:0 auto}
        h1{font-size:18px;margin:0 0 18px}
        .dash-row{background:var(--surface);border:1px solid var(--grid);border-radius:14px;padding:16px;margin-bottom:14px}
        .dash-row-head{display:flex;align-items:center;justify-content:space-between;gap:10px;flex-wrap:wrap}
