/// <summary>قسم في نموذج تصميم حر: عنوانه، وهل يُملأ من بيانات المشروع.</summary>
public sealed record FreeformTemplateSection([property: JsonPropertyName("title")] string Title, [property: JsonPropertyName("needsData")] bool NeedsData = false);

/// <summary>
/// نموذج جاهز لصفحة «تصميم حر» من نوع معيّن (مستند/شرائح/تصميم/لوحة/حركة). النموذج ليس HTML محفوظًا بل
/// موجز بنيوي يُرفق بطلب المستخدم ليبني الموديل الصفحة عليه: الأقسام بترتيبها، وتعليمات الشكل.
/// <c>Sketch</c> رسم تخطيطي للمصغّرة في المعرض: صفوف مفصولة بـ <c>/</c> وكتل بـ <c>,</c>
/// (h عنوان، p فقرة، b نقاط، k3 ثلاث بطاقات مؤشرات، c أعمدة، l خط، d دائري، t جدول، i صورة، f نموذج، g بطاقات، n شريط تنقّل، s شريحة، a مشهد).
/// </summary>
public sealed class FreeformTemplate
{
    [JsonPropertyName("key")] public string Key { get; init; } = "";
    [JsonPropertyName("kind")] public string Kind { get; init; } = "design";
    [JsonPropertyName("category")] public string Category { get; init; } = "general";
    [JsonPropertyName("icon")] public string Icon { get; init; } = "📄";
    [JsonPropertyName("name")] public string Name { get; init; } = "";
    [JsonPropertyName("description")] public string Description { get; init; } = "";
    [JsonPropertyName("sketch")] public string Sketch { get; init; } = "h/p";
    [JsonPropertyName("sections")] public IReadOnlyList<FreeformTemplateSection> Sections { get; init; } = Array.Empty<FreeformTemplateSection>();
    [JsonPropertyName("brief")] public string Brief { get; init; } = "";
    /// <summary>نموذج مرفوع من ملف (مخصص للمشروع) لا من الكتالوج الثابت.</summary>
    [JsonPropertyName("custom")] public bool Custom { get; init; }
    [JsonPropertyName("sourceFile")] public string? SourceFile { get; init; }
    [JsonPropertyName("createdByUserId")] public string? CreatedByUserId { get; init; }
    [JsonPropertyName("createdAt")] public DateTime? CreatedAt { get; init; }
    /// <summary>محتوى نصي مرجعي من الملف المرفوع يُرفق بنظام الموديل؛ لا يُرسل للواجهة.</summary>
    [JsonIgnore] public string? Content { get; init; }
    [JsonPropertyName("dataSections")] public int DataSections => Sections.Count(s => s.NeedsData);
    [JsonPropertyName("total")] public int Total => Sections.Count;
}

